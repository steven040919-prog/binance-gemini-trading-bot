def _infer_asset_class(symbol: str) -> str:
    sym_u = symbol.upper().rstrip("M")
    if any(tok in sym_u for tok in ("BTC", "ETH", "SOL", "XRP", "LTC", "DOGE", "ADA", "BNB")):
        return "CRYPTO"
    if any(tok in sym_u for tok in ("XAU", "XAG", "XPT", "XPD")):
        return "METALS"
    if any(tok in sym_u for tok in ("US500", "USTEC", "US30", "NAS", "SPX", "DAX", "DE40", "UK100", "JP225")):
        return "INDICES"
    if len(sym_u) == 6 and sym_u.isalpha():
        return "FOREX"
    return "OTHER"


def get_scalper_profile(symbol: str) -> SymbolScalperProfile:
    """Return the customized SymbolScalperProfile for `symbol`, with asset-class fallback."""
    if symbol in SCALPER_PROFILES:
        return SCALPER_PROFILES[symbol]

    # Case-insensitive or missing-'m' suffix match against canonical Exness symbols
    sym_clean = symbol.strip()
    for candidate in (sym_clean, f"{sym_clean}m", sym_clean.upper(), f"{sym_clean.upper()}m"):
        if candidate in SCALPER_PROFILES:
            return SCALPER_PROFILES[candidate]

    asset_class = _infer_asset_class(sym_clean)
    base = _ASSET_CLASS_FALLBACKS.get(asset_class, _ASSET_CLASS_FALLBACKS["OTHER"])
    return SymbolScalperProfile(
        symbol=sym_clean or base.symbol,
        asset_class=base.asset_class,
        tier=base.tier,
        risk_multiplier=base.risk_multiplier,
        sl_atr_mult=base.sl_atr_mult,
        tp_atr_mult=base.tp_atr_mult,
        min_rr=base.min_rr,
        be_trigger_atr=base.be_trigger_atr,
        be_lock_atr=base.be_lock_atr,
        trailing_lock_pct=base.trailing_lock_pct,
        stoch_long_max=base.stoch_long_max,
        stoch_short_min=base.stoch_short_min,
        rsi_long_min=base.rsi_long_min,
        rsi_long_max=base.rsi_long_max,
        rsi_short_min=base.rsi_short_min,
        rsi_short_max=base.rsi_short_max,
        max_spread_sl_ratio=base.max_spread_sl_ratio,
        require_candle_pattern=base.require_candle_pattern,
        allow_counter_trend=base.allow_counter_trend,
        min_adx=base.min_adx,
        max_adx=base.max_adx,
        max_body_atr=base.max_body_atr,
        ema_pullback_tol_atr=base.ema_pullback_tol_atr,
    )
